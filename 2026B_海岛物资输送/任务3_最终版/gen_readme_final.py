# ===== MDP README =====
mdp_readme = '''# MDP 值迭代优化方案

## 问题背景

2026B 海岛物资输送问题 任务3：30×30网格，随机天气(p=0.8正常/0.2雷暴)，90天内从B到E最大化目标物资Z。

## 方法论

将问题建模为马尔可夫决策过程(MDP)，在聚合状态空间上进行值迭代求解近似最优策略。

### 状态空间 (1050个状态)

| 维度 | 取值 | 数量 |
|------|------|------|
| 节点 | B, E, W1, W2, W3, S1, S2 | 7 |
| 天气 | 正常, 雷暴 | 2 |
| 资源等级 | critical, low, medium, high, full | 5 |
| 时段 | early(1-30), mid(31-60), late(61-90) | 3 |
| 连续作业 | 0, 1, 2, 3, 4+ 天 | 5 |

### 动作空间

- **MOVE(target)**: 全距离期望消耗转移至目标节点
- **PARK**: 原地停泊，重置连续作业
- **WORK**: 在当前作业点工作（遵守WM约束）
- **SUPPLY**: 在补给点采购资源

### 算法

Bellman最优性方程值迭代：

`
V(s) = max_a [ R(s,a) + γ * Σ P(s'|s,a) * V(s') ]
`

- 收敛阈值: Δ < 1e-4
- 最大迭代: 400
- 折扣因子: γ = 1.0 (有限时域)

### 关键技术特性

- **全距移动消耗**: MOVE动作用完整距离的期望消耗计算资源转移
- **一致量化**: 资源等级正反向映射使用同一组阈值
- **距离感知初始化**: 值函数初值根据到E的距离扣减
- **连续工作追踪**: 精确建模 WM 约束(W1=4, W2=5, W3=3)
- **直接补给计算**: 基于距离的70/30期望-雷暴混合估算补量

## 文件清单

| 文件 | 说明 |
|------|------|
| cp_engine.m | 公共配置/消耗参数引擎 |
| mdp_solver.m | MDP值迭代求解器 + 策略查询 |
| solve_q3_mdp.m | 在线决策主程序 |
| solve_q3_mdp_mc.m | 蒙特卡洛批量验证 |

## 使用方法

`matlab
% 单次MDP在线决策
rng(42); solve_q3_mdp

% 蒙特卡洛验证 (N次随机天气)
rng(42); solve_q3_mdp_mc(100)
`

## 适用场景

- 需要理论最优性分析的场景
- 值函数可解释、可可视化的需求
- 离线策略评估和对比
'''

with open(os.path.join(desktop, 'MDP_值迭代优化方案', 'README.md'), 'w', encoding='utf-8') as f:
    f.write(mdp_readme)

