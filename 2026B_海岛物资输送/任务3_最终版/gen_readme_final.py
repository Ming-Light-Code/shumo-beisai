rso_readme = '''# RSO 滚动随机优化方案

## 问题背景

2026B 海岛物资输送问题 任务3：30×30网格，随机天气(p=0.8正常/0.2雷暴)，90天内从B到E最大化目标物资Z。

## 方法论

借鉴模型预测控制(MPC)，在每一步采样多组天气场景、评估候选动作的期望价值、选择最优动作，实现滚动时域随机优化。

### 算法流程

`
每时间步:
  1. 分层采样 K=48 组天气场景 (前视 H=24天)
  2. 对每个候选动作 (MOVE/PARK/WORK/SUPPLY):
     a. 模拟执行动作的即时消耗 (实际天气)
     b. 全距离移至目标节点或原地执行
     c. 尾部逐日模拟 (贪心策略 + 补给路由)
  3. 选择期望Z最大的动作
  4. 执行一步, 进入下一时间步
`

### 关键技术特性

- **全距移动评估**: MOVE动作模拟完整距离移动（dist步场景天气消耗）后从目标节点开始尾部评估
- **补给路由**: 尾部模拟中资源不足时自动转向最近补给点，形成 工作→补给→E 的完整链路
- **分层采样**: K=48场景中16条强制p(thunder)=0.4，确保雷暴尾部风险被充分覆盖
- **逐日场景模拟**: 尾部使用场景实际天气逐日消耗，非平均消耗近似
- **直接补给计算**: 基于距离的70/30期望-雷暴混合估算补量，替代路径依赖的旧函数
- **连续作业追踪**: 评估和执行中均追踪连续作业天数

### 参数配置

| 参数 | 值 | 说明 |
|------|-----|------|
| H | 24天 | 前视时域(覆盖最长段W2→W3) |
| K | 48 | 总场景数 |
| K_thunder | 16 | 雷暴强化采样数 |
| pN | 0.8 | 正常天气概率 |

## 文件清单

| 文件 | 说明 |
|------|------|
| cp_engine.m | 公共配置/消耗参数引擎 |
| so_solver.m | RSO求解引擎(场景采样/动作评估/尾部模拟) |
| solve_q3_rso.m | 在线决策主程序 |
| solve_q3_rso_mc.m | 蒙特卡洛批量验证 |

## 使用方法

`matlab
% 单次RSO在线决策 (计算量较大)
rng(42); solve_q3_rso

% 蒙特卡洛验证 (N=30-40推荐)
rng(42); solve_q3_rso_mc(30)
`

## 适用场景

- 需要在线自适应决策的场景
- 对计算开销不敏感的环境
- 需要显式建模天气不确定性的需求
'''

