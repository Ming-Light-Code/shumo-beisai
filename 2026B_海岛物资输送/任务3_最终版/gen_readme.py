README_C = """# 优化方案C：滚动随机优化 (Rolling Stochastic Optimization)

## 概述

借鉴模型预测控制 (MPC) 思想，在每一步采样多组天气场景、求解场景确定性CP、选择期望最优动作，实现滚动时域随机优化。

## 方法论

### 算法流程
```
FOR each time step t:
    1. 采样 K=30 组天气场景 (horizon H=10天)
    2. FOR each 候选动作 a:
        模拟执行 a 的即时效果
        FOR each 场景 k:
            从新状态出发，求解确定性CP
            累计场景价值
        计算 a 的期望价值 = Σ 场景价值 / K
    3. 选择期望价值最大的动作 a*
    4. 执行 a*，进入 t+1
```

### 候选动作
- **MOVE(target)**：朝 W1/W2/W3/S1/S2 移动一格
- **PARK**：原地停泊一天
- **WORK**：在作业点工作（仅W1-3）
- **SUPPLY**：在补给点采购（仅S1-2）

### 场景CP求解
对每组采样天气场景，根据场景中正常/雷暴比例构建混合消耗参数，调用 CP 引擎求解剩余路径。

### 关键参数

| 参数 | 值 | 说明 |
|------|-----|------|
| H | 10天 | 前视时域长度 |
| K | 30 | 场景采样数 |
| pN | 0.8 | 正常天气概率 |

## 与方案A/B的区别

| 维度 | 方案A | 方案B | 方案C |
|------|-------|-------|-------|
| 方法论 | 启发式规则 | 值迭代 | 场景采样+CP |
| 决策粒度 | 规则驱动 | 值函数驱动 | 期望最大化 |
| 最优性 | 无保证 | 聚合近似最优 | 采样近似最优 |
| 计算量 | 低 | 中(126状态) | 高(K×CP) |
| 天气建模 | 当前+阈值 | 概率转移 | 显式采样 |

## 文件清单

| 文件 | 说明 |
|------|------|
| `rso_solver.m` | RSO求解引擎（场景采样/动作评估/CP规划） |
| `solve_q3_rso.m` | RSO在线决策主程序 |
| `solve_q3_rso_mc.m` | RSO MC验证 |
| `cp_engine_v2.m` | 复用方案A的引擎 |

## 使用方法

```matlab
% 单次RSO决策 (计算量较大)
rng(42); solve_q3_rso

% MC验证 (N=30-50推荐，单次RSO开销大)
rng(42); solve_q3_rso_mc(30)
```

## 局限性
- 计算开销大：每步需要 K×候选动作数 次CP搜索
- 场景采样有限：K=30 仅覆盖 2^10 种可能天气中的极小部分
- 简化尾部估值：时域末用启发式估算而非精确CP
- 不适合实时要求高的场景
"""
