README_B = """# 优化方案B：MDP方向 (Markov Decision Process)

## 概述

将问题建模为马尔可夫决策过程，在聚合状态空间上进行值迭代，获得近似最优策略。

## 方法论

### 状态空间聚合
将巨大原始状态空间聚合为 7×2×3×3 = 126 个状态：

| 维度 | 取值 | 说明 |
|------|------|------|
| node_id | 1-7 | B, E, W1, W2, W3, S1, S2 |
| weather | 1-Normal, 2-Thunder | 当日天气 |
| resource_level | 1-危急, 2-偏低, 3-正常 | 基于能否以雷暴消耗抵达E |
| day_bucket | 1-Early, 2-Mid, 3-Late | 时段划分 |

### 动作空间
- **MOVE**：朝目标节点移动一格
- **PARK**：原地停泊一天
- **WORK**：在作业点工作（仅W1-3）
- **SUPPLY**：在补给点采购（仅S1-2）

### 值迭代算法
对 126 个状态进行 Bellman 最优性方程迭代：

```
V(s) = max_a [ R(s,a) + γ Σ P(s'|s,a) V(s') ]
```

- 折扣因子 γ = 1.0（有限时域，不折扣）
- 天气转移：P(N|·)=0.8, P(T|·)=0.2（独立同分布）
- 收敛阈值：1e-3

### 策略执行
在线执行时，根据当前聚合状态查表获取最优动作。

## 与方案A的区别

| 维度 | 方案A | 方案B |
|------|-------|-------|
| 方法论 | 启发式规则 | 值迭代优化 |
| 决策方式 | if-else规则 | Bellman方程 |
| 最优性 | 无理论保证 | 聚合状态下的近似最优 |
| 可解释性 | 规则直观 | 值函数可解释 |

## 文件清单

| 文件 | 说明 |
|------|------|
| `mdp_solver.m` | MDP值迭代求解器 + 策略查询 |
| `solve_q3_mdp.m` | MDP在线决策主程序 |
| `solve_q3_mdp_mc.m` | MDP MC验证 |
| `cp_engine_v2.m` | 复用方案A的引擎（配置/补给计算） |

## 使用方法

```matlab
% 单次MDP决策
rng(42); solve_q3_mdp

% MC验证
rng(42); solve_q3_mdp_mc(100)
```

## 局限性
- 状态聚合丢失精细资源信息
- 值函数初始化偏差（乐观初值500）
- 未建模连续工作天数约束
- 收敛性依赖于离散化粒度
"""
